def main() -> None:
    rows = [
        {"text": f"{prefix}{sentence}{suffix}", "label": label}
        for label, sentences in TEMPLATES.items()
        for sentence, prefix, suffix in product(sentences, PREFIXES, SUFFIXES)
    ]
    out = Path(__file__).resolve().parents[1] / "data" / "sample_news.csv"
    out.parent.mkdir(parents=True, exist_ok=True)
    pd.DataFrame(rows).to_csv(out, index=False, encoding="utf-8")
    print(f"Wrote {len(rows)} rows to {out}")


if __name__ == "__main__":
    main()
